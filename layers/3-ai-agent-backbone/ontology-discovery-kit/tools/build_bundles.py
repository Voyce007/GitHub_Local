"""Build the two distributable bundles into dist/.

    python tools/build_bundles.py

dist/ontology-discovery-kit-<version>.zip
    The full kit for Claude Code (CLI, desktop app, IDE extensions, web). Unzip it, then
    `python install.py standalone | project <path> | user`.
dist/ontology-discovery-skill-<version>.zip
    An uploadable skill for Claude apps with code execution and skills (claude.ai, Claude desktop).
    The roles are played in turn; the same pipeline checks the work.
"""
from __future__ import annotations

import re
import shutil
import zipfile
from pathlib import Path

KIT = Path(__file__).resolve().parent.parent
DIST = KIT / "dist"
VERSION = re.search(r'^version = "([^"]+)"', (KIT / "pyproject.toml").read_text(), re.M).group(1)
SKIP_DIRS = {"__pycache__", "work", "dist", ".pytest_cache", "skill-bundle"}


def _walk(root: Path, include):
    for p in sorted(root.rglob("*")):
        rel = p.relative_to(root)
        if any(part in SKIP_DIRS for part in rel.parts) or p.is_dir() or p.suffix == ".pyc":
            continue
        if include(rel):
            yield p, rel


def build_kit() -> Path:
    out = DIST / f"ontology-discovery-kit-{VERSION}.zip"
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for p, rel in _walk(KIT, lambda r: True):
            z.write(p, Path("ontology-discovery-kit") / rel)
    return out


def build_skill() -> Path:
    out = DIST / f"ontology-discovery-skill-{VERSION}.zip"
    base = Path("ontology-discovery")
    keep_scen = ("scenarios/northmere/", "scenarios/meridale/")

    def kit_files(rel: Path) -> bool:
        s = rel.as_posix()
        if s.startswith(("ontokit/", "config/", "schemas/")) or s in ("pyproject.toml", "requirements.txt"):
            return True
        # samples: inputs and scenario files only (outputs are regenerated by `simulate`)
        return s.startswith(keep_scen) and "/outputs/" not in s
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        z.write(KIT / "skill-bundle" / "SKILL.md", base / "SKILL.md")
        for p, rel in _walk(KIT, kit_files):
            z.write(p, base / "kit" / rel)
        for a in sorted((KIT / ".claude" / "agents").glob("*.md")):
            z.write(a, base / "kit" / "roles" / a.name)
    return out


if __name__ == "__main__":
    if DIST.exists():
        shutil.rmtree(DIST)
    DIST.mkdir()
    for f in (build_kit(), build_skill()):
        print(f"{f.relative_to(KIT)}  {f.stat().st_size // 1024} KB")
