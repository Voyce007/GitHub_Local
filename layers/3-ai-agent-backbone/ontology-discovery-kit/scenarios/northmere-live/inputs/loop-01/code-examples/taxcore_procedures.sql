CREATE PROCEDURE PRC_CALC_NIC (IN p_tax_year CHAR(7))
-- Capability: Calculate NI Contributions
BEGIN
  INSERT INTO TC_NI_CONTRIBUTION (EMPLOYMENT_ID, TAX_YEAR, PERIOD_NO, NI_CATEGORY, EMPLOYEE_NIC, EMPLOYER_NIC)
  SELECT p.EMPLOYMENT_ID, p.TAX_YEAR, p.PERIOD_NO, p.NI_CATEGORY,
         (p.GROSS_PAY - 1048) * 0.08, (p.GROSS_PAY - 758) * 0.138
  FROM TC_PAY_PERIOD p
  JOIN TC_EMPLOYMENT e ON e.EMPLOYMENT_ID = p.EMPLOYMENT_ID
  JOIN TC_PERSON per ON per.PERSON_ID = e.PERSON_ID
  WHERE p.TAX_YEAR = p_tax_year AND per.DATE_OF_DEATH IS NULL;
END;

CREATE PROCEDURE PRC_ALLOCATE_NINO (IN p_person_id INTEGER)
-- Capability: Allocate NI Number
BEGIN
  UPDATE TC_PERSON SET NI_NUMBER = NEXT VALUE FOR SEQ_NINO WHERE PERSON_ID = p_person_id;
END;

CREATE PROCEDURE PRC_CHECK_ELIGIBILITY (IN p_account_id INTEGER)
-- Capability: Check Childcare Eligibility
BEGIN
  INSERT INTO TC_ELIGIBILITY_CHECK (CC_ACCOUNT_ID, CHECK_DATE, EXPECTED_INCOME, OUTCOME)
  SELECT a.CC_ACCOUNT_ID, CURRENT DATE, SUM(p.GROSS_PAY) * 4,
         CASE WHEN SUM(p.GROSS_PAY) * 4 > 100000 THEN 'NEL' ELSE 'ELG' END
  FROM TC_CHILDCARE_ACCOUNT a
  JOIN TC_EMPLOYMENT e ON e.PERSON_ID = a.PERSON_ID
  JOIN TC_PAY_PERIOD p ON p.EMPLOYMENT_ID = e.EMPLOYMENT_ID
  WHERE a.CC_ACCOUNT_ID = p_account_id;
END;

CREATE PROCEDURE PRC_CALC_TOPUP (IN p_payment_id INTEGER)
-- Capability: Calculate Childcare Top-up
BEGIN
  UPDATE TC_CHILDCARE_PAYMENT SET TOPUP_AMOUNT = PARENT_AMOUNT * 0.25 WHERE PAYMENT_ID = p_payment_id;
END;

CREATE PROCEDURE PRC_CLOSE_DECEASED ()
-- Capability: Record Life Events
BEGIN
  UPDATE TC_CHILDCARE_ACCOUNT SET STATUS = 'CLO'
  WHERE PERSON_ID IN (SELECT PERSON_ID FROM TC_PERSON WHERE DATE_OF_DEATH IS NOT NULL);
END;
