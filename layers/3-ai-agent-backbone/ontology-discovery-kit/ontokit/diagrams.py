def build(paths: LoopPaths, trace: Trace) -> dict:
    model = read_json(paths.work / "model.json")
    gates = read_json(paths.work / "gates.json") if (paths.work / "gates.json").exists() else []
    els = model["elements"]
    by_id = {e["id"]: e for e in els}
    by_kind = defaultdict(list)
    for e in els:
        by_kind[e["kind"]].append(e)
    pie, gate_flow = conformance(model, gates)
    out = {
        "ba-concept-map": ba_concepts(els, by_kind, by_id),
        "ea-system-context": ea_context(els, by_kind, by_id),
        "ea-capability-map": ea_capabilities(els, by_kind, by_id),
        "da-entity-relationship": da_er(els, by_kind, by_id),
        "eng-calculation-flow": eng_calcs(els, by_kind, by_id),
        "steward-aliases": steward_aliases(model),
        "steward-decomposition": steward_decomposition(model),
        "conformance-grades": pie,
        "conformance-gates": gate_flow if gates else "",
    }
    from . import architecture
    sources = read_json(paths.work / "sources.json")["sources"] if (paths.work / "sources.json").exists() else {}
    arch = architecture.build(model, sources)
    if arch:
        out["aggregate-architecture"] = arch["diagram"]
    return {k: v for k, v in out.items() if v}


def publish(paths: LoopPaths, trace: Trace) -> list[str]:
    diagrams = build(paths, trace)
    d = paths.outputs / "diagrams"
    d.mkdir(parents=True, exist_ok=True)
    for old in d.glob("*.mmd"):
        old.unlink()
    md = [f"# Diagrams — {paths.loop}", "", "Generated from the graded model by `ontokit`, one set per agent. " + LEGEND, ""]
    for key, title, about in SECTIONS:
        if key not in diagrams:
            continue
        (d / f"{key}.mmd").write_text(diagrams[key] + "\n", encoding="utf-8")
        md += [f"## {title}", "", about, "", "```mermaid", diagrams[key], "```", ""]
    (d / "README.md").write_text("\n".join(md), encoding="utf-8")
    trace.emit("L. Diagrams", "Publisher", "diagrams written", f"{len(diagrams)} diagrams: " + ", ".join(diagrams),
               diagrams=list(diagrams))
    return list(diagrams)
