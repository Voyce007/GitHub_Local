"""Stage L — Diagrams: one or more Mermaid diagrams per agent, generated from the published model.

Diagrams are generated by code from the graded elements, never drawn by hand, so
they always match the evidence. Every node is coloured by its evidence grade:
A = confirmed, B = corroborated, C = single source, D = assumed, X = contradicted.

  Business Analyst      ba-concept-map.mmd           business terms, synonyms, the entities that realise them
  Enterprise Architect  ea-system-context.mmd        systems, their roles and the data flows between them
                        ea-capability-map.mmd        capabilities grouped by accountable team
  Data Architect        da-entity-relationship.mmd   entities, keys, attributes and relationships
  Engineer              eng-calculation-flow.mmd     each calculation, the tables it reads (dashed) and writes (solid)
  Ontology Steward      steward-aliases.mmd          system names merged by stated aliases, and unexplained systems
                        steward-decomposition.mmd    target domains, their services, dependencies and events (if decomposed)
  Conformance           conformance-gates.mmd        grade distribution and the status of each phase gate

Output: <root>/outputs/<loop>/diagrams/*.mmd, plus README.md that embeds them all
(it renders on GitHub, in most Markdown viewers, and in Claude artifacts).
"""
from __future__ import annotations

import re
from collections import Counter, defaultdict

from .common import LoopPaths, Trace, human, read_json

GRADE_CLASSES = """
  classDef gA fill:#1d7a4426,stroke:#1d7a44,stroke-width:2px
  classDef gB fill:#2867a026,stroke:#2867a0,stroke-width:2px
  classDef gC fill:#9a621026,stroke:#9a6210,stroke-width:1.5px,stroke-dasharray:4 3
  classDef gD fill:#6b748326,stroke:#6b7483,stroke-dasharray:2 3
  classDef gX fill:#b2382426,stroke:#b23824,stroke-width:2.5px"""
LEGEND = "Node colours show evidence grade: A confirmed · B corroborated · C single source (dashed) · D assumed · X contradicted."
MAX_ATTRS = 8


def _id(s: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", s)


def _lbl(s: str) -> str:
    return str(s).replace('"', "'").replace("\n", " ").replace("[", "(").replace("]", ")").replace("|", "/")


def _cls(lines: list[str], els: list[dict]) -> None:
    lines.append(GRADE_CLASSES)
    groups = defaultdict(list)
    for e in els:
        if e.get("grade"):
            groups[e["grade"]].append(_id(e["id"]))
    for g, ids in sorted(groups.items()):
        lines.append(f"  class {','.join(ids)} g{g}")


def ba_concepts(els, by_kind, by_id) -> str:
    L = ["flowchart LR"]
    concepts = [c for c in by_kind["concept"]]
    shown = []
    doms = defaultdict(list)
    for c in concepts:
        doms[c["properties"].get("domain") or ""].append(c)
    for dom, cs in sorted(doms.items()):
        if dom:
            L.append(f'  subgraph dom_{_id(dom)}["{_lbl(dom)}"]')
        for c in cs:
            mark = "" if c["definition"] else " (undefined)"
            L.append(f'    {_id(c["id"])}(["{_lbl(c["name"])}{mark}"])')
            shown.append(c)
        if dom:
            L.append("  end")
    for c in concepts:
        for a in c["aliases"][:4]:
            sid = _id(f"syn_{c['id']}_{a}")
            L.append(f'  {sid}["{_lbl(a)}"] -. synonym .- {_id(c["id"])}')
        for key in ("realised_by",):
            if (ent := by_id.get(c["properties"].get(key, ""))):
                L.append(f'  {_id(c["id"])} --> {_id(ent["id"])}[("{_lbl(human(ent["name"]))}")]')
                shown.append(ent)
        for eid in c["properties"].get("also_realised_by", []):
            if (ent := by_id.get(eid)):
                L.append(f'  {_id(c["id"])} -- same concept --> {_id(ent["id"])}[("{_lbl(human(ent["name"]))}")]')
                shown.append(ent)
    _cls(L, shown)
    return "\n".join(L)


def ea_context(els, by_kind, by_id) -> str:
    L = ["flowchart LR"]
    systems = by_kind["system"]
    name2id = {s["name"]: _id(s["id"]) for s in systems}
    for s in systems:
        role = (s["properties"].get("roles") or ["role unknown"])[0]
        aka = f"<br/><i>aka {_lbl(', '.join(s['aliases'][:3]))}</i>" if s["aliases"] else ""
        L.append(f'  {_id(s["id"])}["<b>{_lbl(s["name"])}</b><br/>{_lbl(role)}{aka}"]')
    for f in by_kind["flow"]:
        a, b = name2id.get(f["properties"].get("source")), name2id.get(f["properties"].get("target"))
        if a and b:
            lab = _lbl(f["properties"].get("label", ""))[:40]
            L.append(f'  {a} -->|"{lab}"| {b}' if lab else f"  {a} --> {b}")
    _cls(L, systems)
    return "\n".join(L)


def ea_capabilities(els, by_kind, by_id) -> str:
    caps = by_kind["capability"]
    if not caps:
        return ""
    L = ["flowchart TB"]
    teams = defaultdict(list)
    for c in caps:
        teams[c["properties"].get("owner_team") or "Owner unknown"].append(c)
    for i, (team, cs) in enumerate(sorted(teams.items())):
        L.append(f'  subgraph team_{i}["{_lbl(team)}"]')
        L.append("    direction TB")
        for c in cs:
            L.append(f'    {_id(c["id"])}["{_lbl(c["name"])}"]')
        L.append("  end")
    _cls(L, caps)
    return "\n".join(L)


def da_er(els, by_kind, by_id) -> str:
    ents = [e for e in by_kind["entity"] if e["origin"] != "assumed"]
    if not ents:
        return ""
    names = {e["name"] for e in ents}
    ids = {(i["properties"].get("entity_id"), i["properties"].get("attribute")) for i in by_kind["identifier"]}
    L = ["erDiagram"]
    for e in ents:
        L.append(f"  {_id(e['name'])} {{")
        attrs = [by_id[a] for a in e["properties"].get("attribute_ids", []) if a in by_id]
        for a in attrs[:MAX_ATTRS]:
            p = a["properties"]
            typ = re.sub(r"[^A-Za-z]", "", str(p.get("data_type", "string")).split("(")[0]).lower() or "string"
            key = " PK" if (e["id"], p.get("attribute")) in ids else ""
            L.append(f"    {typ} {_id(p.get('attribute', a['name']))}{key} \"grade {a['grade']}\"")
        if len(attrs) > MAX_ATTRS:
            L.append(f"    string plus_{len(attrs) - MAX_ATTRS}_more_attributes \"not shown\"")
        L.append("  }")
    card = {"many-to-one": "}o--||", "one-to-many": "||--o{", "many-to-many": "}o--o{", "one-to-one": "||--||"}
    seen = set()
    for r in by_kind["relationship"]:
        p = r["properties"]
        f, t = p.get("from"), p.get("to")
        if r["origin"] == "assumed" or f not in names or t not in names or (f, t) in seen:
            continue
        seen.add((f, t))
        lab = f"{p.get('via') or 'relates'} ({r['grade']})"
        L.append(f'  {_id(f)} {card.get(p.get("cardinality"), "}o--||")} {_id(t)} : "{_lbl(lab)}"')
    return "\n".join(L)


def eng_calcs(els, by_kind, by_id) -> str:
    calcs = by_kind["calculation"]
    if not calcs:
        return ""
    ents = {e["properties"].get("physical", "").upper(): e for e in by_kind["entity"] if e["properties"].get("physical")}
    L = ["flowchart LR"]
    tables = set()
    doms = defaultdict(list)
    for c in calcs:
        doms[c["properties"].get("domain") or ""].append(c)
    for dom, cs in sorted(doms.items()):
        if dom:
            L.append(f'  subgraph cd_{_id(dom)}["{_lbl(dom)} calculations"]')
        for c in cs:
            title = c["properties"].get("title") or c["name"]
            L.append(f'    {_id(c["id"])}[["{_lbl(title)}<br/><small>{_lbl(c["name"])}</small>"]]')
        if dom:
            L.append("  end")
    for c in calcs:
        for t in c["properties"].get("writes", []):
            tables.add(t)
            cols = [x.split(".", 1)[1] for x in c["properties"].get("writes_columns", []) if x.upper().startswith(t.upper() + ".")]
            lab = f'|"{_lbl(", ".join(cols))}"|' if cols else ""
            L.append(f"  {_id(c['id'])} ==>{lab} tbl_{_id(t)}")
        for t in c["properties"].get("reads", []):
            if t in c["properties"].get("writes", []):
                continue
            tables.add(t)
            L.append(f"  tbl_{_id(t)} -.-> {_id(c['id'])}")
    tdoms = defaultdict(list)
    for t in sorted(tables):
        e = ents.get(t.upper())
        tdoms[(e or {}).get("properties", {}).get("domain") or ""].append((t, e))
    for dom, ts in sorted(tdoms.items()):
        if dom:
            L.append(f'  subgraph td_{_id(dom)}["{_lbl(dom)} data"]')
        for t, e in ts:
            L.append(f'    tbl_{_id(t)}[("{_lbl(t)}")]')
        if dom:
            L.append("  end")
    _cls(L, calcs)
    return "\n".join(L)


def steward_aliases(model) -> str:
    els = model["elements"]
    systems = [e for e in els if e["kind"] == "system"]
    if not systems:
        return ""
    L = ["flowchart LR"]
    for s in systems:
        L.append(f'  {_id(s["id"])}(["<b>{_lbl(s["name"])}</b>"])')
        for i, a in enumerate(s["aliases"]):
            L.append(f'  {_id(s["id"])}_a{i}["{_lbl(a)}"] -- same system --> {_id(s["id"])}')
        if not s["properties"].get("roles"):
            L.append(f'  q_{_id(s["id"])}{{"What is it? Who owns it?"}} -.- {_id(s["id"])}')
    _cls(L, systems)
    return "\n".join(L)


def steward_decomposition(model) -> str:
    dec = model.get("decomposition")
    if not dec:
        return ""
    names = {d["key"]: d["name"] for d in dec["domains"]}
    L = ["flowchart LR"]
    for d in dec["domains"]:
        k = d["key"]
        L.append(f'  subgraph {_id(k)}["{_lbl(d["name"])}<br/><small>{_lbl(d.get("owner", ""))}</small>"]')
        L.append("    direction TB")
        ents = dec["summary"][k].get("entities", [])
        if ents:
            L.append(f'    {_id(k)}_data[("{_lbl(", ".join(human(e) for e in ents))}")]')
        for i, s in enumerate(dec["services"][k]):
            shape = ('[["', '"]]') if s["type"] == "event" else ('(["', '"])') if s["type"] == "query" else ('["', '"]')
            L.append(f"    {_id(k)}_s{i}{shape[0]}{_lbl(s['name'])}{shape[1]}")
        L.append("  end")
    for d in dec["domains"]:
        for i, s in enumerate(dec["services"][d["key"]]):
            for c in s.get("consumers", []):
                L.append(f"  {_id(c)} {'-. reacts to .->' if s['type'] == 'event' else '-- uses -->'} {_id(d['key'])}_s{i}")
    for sp in dec.get("splits", []):
        L.append(f'  {_id(sp["from"])}_data -. "{_lbl(sp["column"])} moves" .-> {_id(sp["to"])}')
    return "\n".join(L)


def conformance(model, gates) -> str:
    g = Counter(e["grade"] for e in model["elements"])
    L = ['pie showData title Evidence grades']
    labels = {"A": "A confirmed", "B": "B corroborated", "C": "C single source", "D": "D assumed", "X": "X contradicted"}
    for k in "ABCDX":
        if g.get(k):
            L.append(f'  "{labels[k]}" : {g[k]}')
    pie = "\n".join(L)
    G = ["flowchart LR"]
    prev = None
    colour = {"pass": "gA", "provisional": "gC", "fail": "gX"}
    for ph in gates:
        nid = f"P{ph['phase']}"
        G.append(f'  {nid}["Phase {ph["phase"]}<br/>{_lbl(ph["name"])}<br/><b>{ph["status"].upper()}</b><br/>'
                 f'<small>{ph["below_B"]} of {ph["in_scope"]} below B</small>"]')
        if prev:
            G.append(f"  {prev} --> {nid}")
        prev = nid
    G.append(GRADE_CLASSES)
    for ph in gates:
        G.append(f"  class P{ph['phase']} {colour.get(ph['status'], 'gD')}")
    return pie, "\n".join(G)


